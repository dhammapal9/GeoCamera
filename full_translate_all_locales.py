def escape_xml(text):
    if not text:
        return ""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    parts = re.split(r"(\\')", text)
    res = []
    for p in parts:
        if p == "\\'":
            res.append(p)
        else:
            res.append(p.replace("'", "\\'"))
    return "".join(res)

base_path = 'app/src/main/res'
for val_dir in sorted(glob.glob(os.path.join(base_path, 'values-*'))):
    if val_dir.endswith('values-night'):
        continue
    folder_name = os.path.basename(val_dir)
    lang_code = folder_name.replace('values-', '').split('-')[0]
    s_file = os.path.join(val_dir, 'strings.xml')
    if not os.path.exists(s_file):
        continue

    try:
        t = ET.parse(s_file)
        r = t.getroot()
        existing = {e.attrib.get('name'): e for e in r.findall('string')}

        updated_count = 0
        lang_dict = TRANSLATIONS.get(lang_code, {})

        for elem in r.findall('string'):
            k = elem.attrib.get('name')
            if k in lang_dict:
                elem.text = lang_dict[k]
                updated_count += 1

        if updated_count > 0:
            xml_lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
            for child in r.findall('string'):
                k = child.attrib.get('name')
                v = child.text or ''
                escaped_v = escape_xml(v)
                xml_lines.append(f'    <string name="{k}">{escaped_v}</string>')
            xml_lines.append('</resources>')
            xml_lines.append('')

            with open(s_file, 'w', encoding='utf-8') as f:
                f.write('\n'.join(xml_lines))
            print(f"Updated {folder_name}: applied {updated_count} translations.")

    except Exception as err:
        print(f"Error processing {s_file}: {err}")
