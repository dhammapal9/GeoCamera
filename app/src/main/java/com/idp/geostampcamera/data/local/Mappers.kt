package com.idp.geostampcamera.data.local

import com.idp.geostampcamera.domain.model.CapturedPhoto
import com.idp.geostampcamera.domain.model.StampTemplate

fun PhotoEntity.toDomain(): CapturedPhoto = CapturedPhoto(
    id = id,
    originalPath = originalPath,
    stampedPath = stampedPath,
    publicUri = publicUri,
    timestampMillis = timestampMillis,
    latitude = latitude,
    longitude = longitude,
    shortAddress = shortAddress,
    fullAddress = fullAddress,
    accuracyMeters = accuracyMeters,
    altitudeMeters = altitudeMeters,
    templateId = templateId,
    note = note,
    projectName = projectName,
    mapType = mapType,
    widthPx = widthPx,
    heightPx = heightPx,
    status = runCatching { CapturedPhoto.Status.valueOf(status) }.getOrDefault(CapturedPhoto.Status.READY)
)

fun CapturedPhoto.toEntity(): PhotoEntity = PhotoEntity(
    id = id,
    originalPath = originalPath,
    stampedPath = stampedPath,
    publicUri = publicUri,
    timestampMillis = timestampMillis,
    latitude = latitude,
    longitude = longitude,
    shortAddress = shortAddress,
    fullAddress = fullAddress,
    accuracyMeters = accuracyMeters,
    altitudeMeters = altitudeMeters,
    templateId = templateId,
    note = note,
    projectName = projectName,
    mapType = mapType,
    widthPx = widthPx,
    heightPx = heightPx,
    status = status.name
)

fun TemplateEntity.toDomain(): StampTemplate = StampTemplate(
    id = id,
    name = name,
    type = runCatching { StampTemplate.TemplateType.valueOf(type) }.getOrDefault(StampTemplate.TemplateType.CUSTOM),
    layout = runCatching { StampTemplate.LayoutStyle.valueOf(layout) }.getOrDefault(StampTemplate.LayoutStyle.HORIZONTAL),
    backgroundArgb = backgroundArgb,
    backgroundAlpha = backgroundAlpha,
    textArgb = textArgb,
    accentArgb = accentArgb,
    fontScale = fontScale,
    cornerRadiusDp = cornerRadiusDp,
    borderDp = borderDp,
    borderArgb = borderArgb,
    mapSize = runCatching { StampTemplate.MapSize.valueOf(mapSize) }.getOrDefault(StampTemplate.MapSize.MEDIUM),
    coordinateFormat = runCatching { StampTemplate.CoordFormat.valueOf(coordinateFormat) }.getOrDefault(StampTemplate.CoordFormat.DECIMAL),
    dateFormat = dateFormat,
    timeFormat = timeFormat,
    timezoneId = timezoneId,
    tempUnit = runCatching { StampTemplate.TempUnit.valueOf(tempUnit) }.getOrDefault(StampTemplate.TempUnit.CELSIUS),
    altitudeUnit = runCatching { StampTemplate.AltitudeUnit.valueOf(altitudeUnit) }.getOrDefault(StampTemplate.AltitudeUnit.METERS),
    showMap = showMap,
    showShortAddress = showShortAddress,
    showFullAddress = showFullAddress,
    showCoordinates = showCoordinates,
    showPlusCode = showPlusCode,
    showDateTime = showDateTime,
    showAltitude = showAltitude,
    showAccuracy = showAccuracy,
    showSpeed = showSpeed,
    showBearing = showBearing,
    showCompass = showCompass,
    showMagnetic = showMagnetic,
    showWeather = showWeather,
    showLogo = showLogo,
    showNote = showNote,
    note = note,
    hashtag = hashtag,
    projectName = projectName,
    businessName = businessName,
    reference = reference,
    logoUri = logoUri,
    isBuiltIn = isBuiltIn,
    fontFamily = runCatching { StampTemplate.FontFamily.valueOf(fontFamily) }.getOrDefault(StampTemplate.FontFamily.SANS),
    fieldOrder = fieldOrder,
    updatedAtMillis = updatedAtMillis
)

